#!/usr/bin/env node
/**
 * **装 git hook：让判据在"推之前"必跑**（2026-11-16 · 批次 0 · 对外标准「判据入口必须真的被调用」）。
 *
 * ══ 它治的病 ══════════════════════════════════════════════════════════════════
 *   改前：本仓有 **50 族判据**（`check:all` 聚合入口）、有 `ASSERTION_FLOORS` 与
 *   `FAMILY_FLOOR` 两条下界，**但没有任何东西要求它跑** ——
 *     · `package.json` 的 `build` 只做 `tsc && build:client && write-build-stamp`；
 *     · `.git/hooks/` 里只有 `*.sample`（全是 git 自带的样例，**一个都没启用**）；
 *     · 没有 `.github/`（无 CI），也没有 husky / lint-staged。
 *   ⇒ ⚠ 这与「判据建好了、却没人往里送东西」是同族形态（`E-122`）：
 *     判据的价值是**在改动流经的那条路上开火**，而不是"在别人记得的时候开火"。
 *
 *   ⚠ ⚠ **本脚本不声称"CI 已就位"** —— 它只装一个**本地** hook。
 *     真 CI（服务端强制）需要用同一入口 `npm run verify`，⛔ 本脚本不替你配。
 *
 * ══ 装什么（只有一处，⛔ 不扩散）═══════════════════════════════════════════════
 *   `.git/hooks/pre-push` ⇒ `npm run verify`（= `npm run build && npm run check`）。
 *
 *   ⚠ **为什么是 pre-push 而不是 pre-commit**：
 *     · `verify` 要跑 build + 50 族（实测 60–90 秒量级）⇒ 放 pre-commit 会让人
 *       **普遍开始用 `--no-verify`**，而"人人绕过"的钩子等于没有钩子；
 *     · pre-push 的语义正好是"这份工作要出去了"，与"判据必须过"对齐。
 *
 * ══ 安全（⛔ 不许静默覆盖别人的 hook）══════════════════════════════════════════
 *   · 目标不存在 ⇒ 写入；
 *   · 目标存在且**本脚本写的**（首行 OUR_MARKER）⇒ 覆盖（幂等）；
 *   · 目标存在且**不是我们的** ⇒ **报错退出 1，不覆盖**，并打印冲突路径。
 *     ⚠ 这条是刻意的：hook 是开发者的本地资产，覆盖别人的 hook 属于不可逆动作。
 *
 * 用法：`npm run install-hooks`
 * 退出码：0 = 已安装（或已是最新）· 1 = 拒绝覆盖 / 写失败（⛔ 不静默当作成功）
 * ⚠ 零第三方依赖（本仓纪律）。
 */
import { chmodSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

/** 本脚本写的 hook 的第一行标记（⛔ 别改：改了就认不出自己写的那一份）。 */
export const OUR_MARKER = '# dsh-hob:managed-hook (regenerated by `npm run install-hooks`)'

/**
 * 目标 hook 路径。
 * @param {string} repoRoot
 * @returns {string}
 */
export function prePushPath(repoRoot) {
  return join(repoRoot, '.git', 'hooks', 'pre-push')
}

/**
 * pre-push hook 的正文。
 * ⚠ `set -e` 必须留：否则 `npm run verify` 失败后 shell 仍以 hook 末尾命令的退出码为准，
 *   而那样"判据红了"会被当成"推送放行"（正是本 hook 要防的那件事）。
 * @returns {string}
 */
export function prePushBody() {
  return [
    '#!/bin/sh',
    OUR_MARKER,
    '#',
    '# 为什么在这里：本仓 50 族判据只有 `npm run check` 一个入口，而没有任何东西要求它跑。',
    '# pre-push 是"这份工作要出去了"的那一刻 —— 判据必须在这条路上开火。',
    '# ⚠ 临时绕过：`git push --no-verify`（⛔ 但那样这次推送就没人替你检查了）。',
    'set -e',
    'npm run verify',
    '',
  ].join('\n')
}

/**
 * 判断一份已有 hook 是不是本脚本写的。
 * @param {string} src
 * @returns {boolean}
 */
export function isOurs(src) {
  return String(src).includes(OUR_MARKER)
}

/**
 * 装 hook。
 *
 * @param {string} repoRoot - 仓库根
 * @param {{dryRun?: boolean}} [opts]
 * @returns {{ok: boolean, action: 'created'|'updated'|'unchanged'|'refused'|'failed', path: string, why?: string}}
 */
export function installPrePush(repoRoot, opts = {}) {
  const target = prePushPath(repoRoot)
  const body = prePushBody()
  let existing = null
  try {
    if (existsSync(target)) existing = readFileSync(target, 'utf8')
  } catch (e) {
    return { ok: false, action: 'failed', path: target, why: `读不到已有 hook：${String(e?.message ?? e)}` }
  }
  if (existing !== null && !isOurs(existing)) {
    return {
      ok: false,
      action: 'refused',
      path: target,
      why: '目标已存在且**不是本脚本写的** ⇒ 拒绝覆盖（hook 是本地资产；请先自行备份/删除）',
    }
  }
  if (existing === body) return { ok: true, action: 'unchanged', path: target }
  if (opts.dryRun === true) return { ok: true, action: existing === null ? 'created' : 'updated', path: target }
  try {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, body, 'utf8')
    // ⚠ 可执行位必须在写完之后设：某些文件系统上先 chmod 再写会把模式重置。
    chmodSync(target, 0o755)
    return { ok: true, action: existing === null ? 'created' : 'updated', path: target }
  } catch (e) {
    return { ok: false, action: 'failed', path: target, why: String(e?.message ?? e) }
  }
}

/** 是否在 git 仓里（`.git` 目录在）—— 只做存在性判断，⛔ 不假设它一定是目录（worktree 里是文件）。 */
export function hasGitDir(repoRoot) {
  return existsSync(join(repoRoot, '.git'))
}

if (process.argv[1] !== undefined && process.argv[1].endsWith('install-hooks.mjs')) {
  if (!hasGitDir(root)) {
    console.error(`✗ ${root}${sep} 下没有 .git ⇒ 不是 git 仓，装不了 hook`)
    process.exit(1)
  }
  const r = installPrePush(root, { dryRun: process.argv.includes('--dry-run') })
  if (!r.ok) {
    console.error(`✗ 安装失败（${r.action}）：${r.path}`)
    if (r.why !== undefined) console.error(`   ${r.why}`)
    process.exit(1)
  }
  console.log(`✓ pre-push hook ${r.action}：${r.path}`)
  console.log('  它会在每次 git push 前跑 `npm run verify`（= build + 50 族判据）。')
}
