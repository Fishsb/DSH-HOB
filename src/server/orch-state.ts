/**
 * 把数组字段读成 {@link PersistedWatchEntry}[]（逐条收窄，坏的丢掉）。
 *
 * ⚠ **收窄口径（⚠ 刻意严，因为下游要据它决定"叫醒谁"）**：
 *   · `owner` 必须是非空字符串 —— ⛔ **不许猜一个默认 owner**（`§5.2`/`D15`）；
 *   · `targets` 只收非空字符串、**去重**（同一个会话派两次只算一个观察对象）；
 *   · `state` 只认 `waiting` / `awake` 两个值 —— ⚠ **不认识的取值整条丢掉**，
 *     ⛔ **不许"猜成等待"**：那是"两种原因说成同一句话"（`R-10`）的形态。
 *   · `stateAt` 必须是有限数（判据的"持续多久"靠它）。
 *   ⚠ 一条坏记录**只丢自己**，⛔ 不连坐整张表（同 `asWatchList` / `asBindingList` 纪律）。
 */
function asWatchEntryList(v: unknown): PersistedWatchEntry[] {
  if (!Array.isArray(v)) return []
  const out: PersistedWatchEntry[] = []
  for (const item of v) {
    if (item === null || typeof item !== 'object') continue
    const o = item as Record<string, unknown>
    if (typeof o.owner !== 'string' || o.owner === '') continue
    if (o.state !== 'waiting' && o.state !== 'awake') continue
    if (typeof o.stateAt !== 'number' || !Number.isFinite(o.stateAt)) continue
    const rawTargets = Array.isArray(o.targets) ? o.targets : []
    const targets: string[] = []
    for (const t of rawTargets) {
      if (typeof t !== 'string' || t === '') continue
      if (targets.includes(t)) continue
      targets.push(t)
    }
    const e: PersistedWatchEntry = { owner: o.owner, targets, state: o.state, stateAt: o.stateAt }
    if (typeof o.note === 'string' && o.note !== '') e.note = o.note
    /** ⚠ `D16` 的两枚投递进度标记：类型不对就**不填**（⛔ 不猜、⛔ 不判坏整条）。 */
    if (typeof o.wakeLoggedAt === 'number' && Number.isFinite(o.wakeLoggedAt)) e.wakeLoggedAt = o.wakeLoggedAt
    if (typeof o.wakeDeliveredAt === 'number' && Number.isFinite(o.wakeDeliveredAt)) e.wakeDeliveredAt = o.wakeDeliveredAt
    /**
     * ⚠ 包 BG（兜底）：**叫过几次**。
     *   · 类型不对 / 负数 ⇒ **不填**（读成 0 = 从没叫过，⚠ 不是猜 1：猜 1 会让
     *     一条旧记录**凭空少掉一次机会**）；
     *   · ⚠ 旧盘没有它 ⇒ 也是不填 ⇒ 读成 0 —— 这与"包 AJ 之后那些一次都没按本规则
     *     计过数"的事实一致（如实，⛔ 不是编）。
     */
    if (typeof o.wakeAttempts === 'number' && Number.isFinite(o.wakeAttempts) && o.wakeAttempts >= 0) {
      e.wakeAttempts = Math.floor(o.wakeAttempts)
    }
    out.push(e)
  }
  return out
}

/**
 * 把一个**已解析的普通对象**收窄成 {@link OrchStateFile}（⚠ 缺字段一律按宽容口径读）。
 *
 * ⚠ 抽出来是为了让 {@link readOrchState} 与 {@link readOrchStateDetailed}
 *   **共用同一份收窄实现** —— 否则"两处各写一份"必然漂移（本仓分层纪律）。
 */
function narrowOrchState(o: Record<string, unknown>): OrchStateFile {
  const out: OrchStateFile = {
    version: typeof o.version === 'number' ? o.version : ORCH_STATE_VERSION,
    updatedAt: typeof o.updatedAt === 'number' ? o.updatedAt : 0,
    pending: asWatchList(o.pending),
    lost: asWatchList(o.lost),
    // ⚠ **向后兼容**（本轮核心要求之一）：旧文件没有 `handoffs` 字段 ⇒
    //   `asHandoffList(undefined)` = `[]` ⇒ 读成**空数组**，**不抛、不判坏**。
    //   这正与 `lost` 同款纪律：缺字段 ≠ 文件坏了（运行态是诊断用途）。
    handoffs: asHandoffList(o.handoffs),
    // ⚠ **向后兼容**（`I-6`）：旧文件没有 `sessions` ⇒ 空数组（⛔ 不判坏、⛔ 不猜归属）
    sessions: asBindingList(o.sessions),
    /** ⚠ **向后兼容**（包 H）：旧文件没有 `closed` ⇒ 空数组（⛔ 不判坏、⛔ 不猜）。 */
    closed: asWatchList(o.closed),
    /** ⚠ **向后兼容**（包 AB）：旧文件没有 `watchEntries` ⇒ 空数组（⛔ 不判坏、⛔ 不猜状态）。 */
    watchEntries: asWatchEntryList(o.watchEntries),
    /** ⚠ **向后兼容**（包 AG）：旧文件没有它 ⇒ 不填（= "从没武装过"，⛔ 不猜一个时刻）。 */
    ...(typeof o.watchTimerArmedAt === 'number' && Number.isFinite(o.watchTimerArmedAt)
      ? { watchTimerArmedAt: o.watchTimerArmedAt } : {}),
    /** ⚠ 包 J 3.5：滚出记账（同一条宽容纪律 —— 类型不对就不填）。 */
    ...(typeof o.closedDroppedCount === 'number' && Number.isFinite(o.closedDroppedCount)
      ? { closedDroppedCount: o.closedDroppedCount }
      : {}),
    ...((() => {
      const v = o.closedDroppedLast as unknown
      if (v === null || typeof v !== 'object') return {}
      const t = (v as { target?: unknown }).target
      const a = (v as { at?: unknown }).at
      if (typeof t !== 'string' || t === '') return {}
      if (typeof a !== 'number' || !Number.isFinite(a)) return {}
      return { closedDroppedLast: { target: t, at: a } }
    })()),
  }
  if (typeof o.lostAt === 'number' && Number.isFinite(o.lostAt)) out.lostAt = o.lostAt
  return out
}

/**
 * 读落盘状态（**宽容**：文件不在/坏了/结构不对 ⇒ 空态，绝不抛）。
 *
 * ⚠ 判据是"能不能用"，不是"文件在不在"：`readFileSync` 成功但内容不是 JSON
 *   必须与"文件不存在"走同一条路 —— 否则一个被写坏的文件会让编排模块
 *   在每次 `status()` 时抛异常。
 *
 * ⚠ ⚠ **本函数的分辨力已知不足**（2026-10-16 第 247 轮 · `TASK-R207`）：
 *   它把"**够不到账本**"与"**真的没有记录**"读成**同一个空态**。
 *   ⚠ **要分辨 ⇒ 用 {@link readOrchStateDetailed}**（⚠ 本函数**原样保留**：
 *   既有调用点与 `check:orch` 的 F1/F3 都按它的形状取值，⛔ 不改签名）。
 */
export function readOrchState(file: string): OrchStateFile {
  try {
    const raw = readFileSync(file, 'utf8')
    const parsed: unknown = JSON.parse(raw)
    if (parsed === null || typeof parsed !== 'object') return emptyOrchState()
    return narrowOrchState(parsed as Record<string, unknown>)
  } catch {
    return emptyOrchState()
  }
}

/**
 * 原子写落盘状态（同目录 tmp → rename）。
 *
 * @returns 是否写成功。**失败不抛** —— 由调用方记日志（一个记不上账的
 *   诊断不该让编排的主流程崩掉；但也绝不静默：返回值必须被消费）。
 */
/**
 * ══════════════════════════════════════════════════════════════════════
 * ⚠⚠ **进程内单写者队列**（2026-10-21 · 第 338 轮 · **丙-5**）
 * ══════════════════════════════════════════════════════════════════════
 *
 * ── 为什么需要它（`PROJECT-SURVEY-3` §6.3 丙-5）────────────────────────
 *   全仓 `grep -rnE "O_EXCL|flock|lockfile|withLock|mutex|\.lock'"` 在 `src/` + `scripts/`
 *   = **0 命中** ⇒ 五个写函数全是**无锁的「读 → 改 → 写」**。
 *   ⚠ `writeOrchState` 的 `tmp → rename` 只防**半截文件**，⛔ **不防丢更新**：
 *     A 读到旧盘 → B 读旧盘 → B 写 → A 写 ⇒ **B 的改动被 A 的旧快照覆盖掉**。
 *   ⚠ 而 `orchestrator.persistOwnerPartition` 与 `bus.noteHandoff` 写**同一个文件**、
 *     两个模块各自持有一份快照 ⇒ 这正是"必然丢更新"的形态。
 *
 * ── 做法：Q8 选项 ① · 进程内单写者队列 ────────────────────────────────
 *   ⚠ 为什么不用锁文件：那会引入**新的失败面**（死锁 / 残留锁 / 崩溃后无人清理），
 *     而本进程内的写者本来就都在同一个 Node 进程里。
 *   ⛔ 不引入定时器（`T5`「空闲零定时器」）；⛔ 不改任何调用方的返回值语义与异步性 ——
 *     五个写函数仍**同步返回**，队列在**当前调用栈内**跑完。
 */
export interface OrchWriteQueueStats {
  /** 当前**正在跑**的写事务数（0 = 空闲；>1 = 发生过重入）。 */
  depth: number
  /** 自进程启动以来**累计**入队过多少次。 */
  total: number
  /** 是否**曾经发生过重入**（= 有写事务在自己的读改写中间又调了写函数）。 */
  waited: boolean
  /** 跨进程锁失败次数（0 = 从未撞锁；供读数面区分"写失败"与"拒绝争抢"）。 */
  lockRejected: number
}

const queueStats: OrchWriteQueueStats = { depth: 0, total: 0, waited: false, lockRejected: 0 }
let inWrite = false

/**
 * ⚠ `runSerialized` 只防**同一进程里的重入**。本插件的账本文件会被多个 DSH
 *   Web 进程同时写（本机曾同时跑 web / superagent），所以写事务的**最外层**
 *   还需要跨进程锁；内层嵌套不再重复拿锁。
 */
let crossProcessDepth = 0
/**
 * 同进程内所有模块实例共享的**活锁表**（跨 `apply` / fiber reload）。
 * ⚠ 这不能放在可被重载的模块作用域里：旧 fiber 的 `drain` 仍持旧模块实例，
 *   若它只认自己的表，就会放掉新 fiber 的锁，留下“锁已丢但 writer 还在”的窗口。
 */
const LIVE_ORCH_LOCKS: Map<string, string> = ((globalThis as any).__dshHobOrchLocks ??=
  new Map<string, string>())
/**
 * 当前**最外层事务拿锁失败**的文件。
 *
 * ⚠ 拿不到锁时不能抛给调用方：这些写函数的既有契约是 `wrote:false` 之类，
 *   抛异常会把“拒绝争抢”变成主流程崩溃。做法是：跳过真正的读改写，让
 *   {@link readOrchStateForWrite} 按既有「拒写」形状返回，原函数照常回失败。
 */
let crossProcessDeniedFile: string | undefined

interface OrchLockRecord {
  pid?: unknown
  identity?: unknown
  at?: unknown
}

function recoverAbandonedOrchLock(lockPath: string): boolean {
  let rec: OrchLockRecord
  try {
    rec = JSON.parse(readFileSync(lockPath, 'utf8')) as OrchLockRecord
  } catch {
    return false
  }
  const pid = typeof rec.pid === 'number' && Number.isSafeInteger(rec.pid) && rec.pid > 0 ? rec.pid : undefined
  if (pid === undefined || pid === process.pid) return false
  let alive: boolean | undefined
  try { alive = procProcessAlive(pid) } catch { alive = undefined }
  if (alive !== false) return false
  const quarantine = `${lockPath}.stale-${pid}-${Date.now()}-${Math.random().toString(36).slice(2)}`
  try {
    renameSync(lockPath, quarantine)
    return true
  } catch {
    return false
  }
}

function noteLockRejected(file: string, error: unknown): void {
  try {
    writeRefusals.set(file, {
      reason: 'store-unreadable',
      message: `拒绝写入：运行态文件 \`${file}\` 的跨进程 writer 锁未取得 —— `
        + `${String((error as Error)?.message ?? error)}。`
        + '\n      ⇒ 这是「另一个 live 进程正在写」或「锁主判不出」，不是空账本；'
        + '本进程未做任何 read-modify-write。',
      at: Date.now(),
    })
  } catch { /* 登记失败不掩盖主错误 */ }
}

function acquireOrchLock(file: string): () => void {
  const lockPath = `${file}.lock`
  const identity = `${process.pid}:${Date.now()}:${Math.random().toString(36).slice(2)}`
  mkdirSync(dirname(lockPath), { recursive: true })
  let fd: number
  try {
    fd = openSync(lockPath, 'wx')
  } catch (e: any) {
    /**
     * ⚠ 目录本身不可写时，**任何** writer（包括本进程）都不能落盘。
     *   ⇒ 放行读改写走到既有的 `writeOrchState` 失败路径，保留“清账失败”
     *     等既有可观测行为；⛔ 不把“目录只读”误报成“另一个 writer 活着”。
     *   ⚠ 这不会打开双写窗口：连锁文件都创建不了的目录，也不可能产生并发写。
     */
    if (e?.code === 'EACCES' || e?.code === 'EROFS' || e?.code === 'ENOTDIR') {
      if (typeof process.getuid === 'function' && process.getuid() === 0
        && existsSync(dirname(lockPath))) {
        /**
         * ⚠ root 会绕过 `chmod 0555`，因此权限位无法模拟“清账失败”。
         *   只有显式测试模式才走故障注入；生产（无该环境变量）仍 fail-closed。
         */
        const fail = process.env.DSH_HOB_TEST_FAIL_ORCH_WRITE === '1'
        return () => { if (fail) throw new Error('orch-state-test-write-failed') }
      }
      return () => {}
    }
    if (e?.code !== 'EEXIST' || !recoverAbandonedOrchLock(lockPath)) {
      throw new Error(`orch-state-locked: ${file} 已有跨进程 writer（锁：${lockPath}）`)
    }
    try {
      fd = openSync(lockPath, 'wx')
    } catch (retry: any) {
      if (retry?.code === 'EEXIST') {
        throw new Error(`orch-state-locked: ${file} 锁接管竞争失败（锁：${lockPath}）`)
      }
      throw retry
    }
  }
  try {
    writeFileSync(fd, JSON.stringify({ pid: process.pid, identity, at: Date.now() }))
  } finally {
    closeSync(fd)
  }
  LIVE_ORCH_LOCKS.set(file, identity)
  /**
   * ⚠ 必须显式把 lockPath 绑进释放闭包：`file` 参数在图里是 `string`，
   *   而 `readdirSync` 等路径也共用 `file` 名字；闭包里再拼会引入歧义。
   */
  return function releaseOrchLock(): void {
    try {
      const raw = JSON.parse(readFileSync(lockPath, 'utf8')) as { identity?: unknown }
      if (raw.identity === identity || LIVE_ORCH_LOCKS.get(file) === identity) rmSync(lockPath, { force: true })
    } catch { /* 不冒删别人的锁的风险 */ }
    LIVE_ORCH_LOCKS.delete(file)
  }
}

/** 读队列读数（**只读快照**）。⚠ 正常档（`waited === false`）调用方**不许印任何行**。 */
export function orchWriteQueueStats(): OrchWriteQueueStats {
  return {
    depth: queueStats.depth,
    total: queueStats.total,
    waited: queueStats.waited,
    lockRejected: queueStats.lockRejected,
  }
}

/**
 * 在**单写者**保护下跑一段写事务（同步）。
 *
 * ⚠ **同步执行**：回调在当前调用栈内跑完，返回值原样返回（⛔ 不排队、不延后）。
 * ⚠ **最外层拿跨进程锁**：`open(...,'wx')` → 事务 → 身份核对后删除；
 *   内层 `runSerialized` 复用同一把锁（`crossProcessDepth > 0`）。
 *   ⚠ 锁主确认已死时原子隔离陈旧锁；仍存活 / 判不出 / 锁坏 ⇒ fail-closed
 *   并登记拒写原因。⛔ 不按锁年龄猜，也⛔ 不在没拿到锁时继续改盘。
 * ⚠ **重入如实记账**：进入时若已在写 ⇒ `waited = true`（这说明调用链里有写事务嵌套，
 *   也就是丢更新的形成机制）。⛔ 不在这里抛 —— 那会把记账缺陷变成主流程崩溃。
 */
export function runSerialized<T>(file: string, fn: () => T): T {
  queueStats.total++
  if (inWrite) queueStats.waited = true
  queueStats.depth++
  const prev = inWrite
  inWrite = true
  const needCrossLock = crossProcessDepth === 0 && crossProcessDeniedFile === undefined
  let releaseCross: (() => void) | undefined
  let deniedHere = false
  try {
    if (needCrossLock) {
      try {
        releaseCross = acquireOrchLock(file)
      } catch (e) {
        queueStats.lockRejected++
        noteLockRejected(file, e)
        /**
         * ⚠ 延续既有失败返回，不抛异常；本次事务随后由
         *   {@link readOrchStateForWrite} 统一拒绝并留下可读原因。
         */
        crossProcessDeniedFile = file
        deniedHere = true
      }
      if (!deniedHere) crossProcessDepth++
    }
    return fn()
  } finally {
    if (needCrossLock && !deniedHere) {
      crossProcessDepth--
      releaseCross?.()
    }
    if (deniedHere) crossProcessDeniedFile = undefined
    queueStats.depth--
    inWrite = prev
  }
}

export function writeOrchState(file: string, state: OrchStateFile): boolean {
  const tmp = `${file}.tmp-${process.pid}-${Date.now()}`
  /**
   * ⚠⚠ **D12 回读验证（2026-10-27 · 包 X）**：写成功不等于**盘上**成功。
   *
   * ── 改前（本函数就是那个形态）──────────────────────────────────────────
   *   `renameSync` 返回 ⇒ 直接 `return true`。⚠ 而实测过的真机故障正是
   *   「`ok:true` 而盘上没写」（`CHG-086`）：**调用方以为落盘了，读数却是旧的**。
   *
   * ── 现在：三条判据（`D12` §5.6 逐条落）─────────────────────────────────
   *   ① **对着预期值比**，⛔ 不是"文件存在"：序列化后的 `expect` 与盘上**逐字节**比；
   *   ② **回读失败 ⇒ 返回 `false`**（⛔ 不许因为"我已经调过写函数"就报成功）；
   *   ③ **回读必须是独立的一次读**：用 `readFileSync` **重新从盘上读**，
   *      ⛔ 不是"看一眼刚序列化的内存对象"（那就是改前那个形态的变种）。
   *
   * ⚠ **为什么读的是 `Buffer` 再转串**：`readFileSync(p,'utf8')` 会静默做解码替换，
   *   坏字节会变成 `U+FFFD` 而**与预期串仍然不等**（结果一样）；取 Buffer 是为了让
   *   "长度先比"这一步有意义（报得出 `实际 N 字节 / 期望 M 字节`）。
   * ⚠ **失败不回滚**：本函数**没有**备份（运行态不是账本），回滚无可回。
   *   但**必须让调用方看见失败** —— 那正是 `D12` 要的"返回失败"。
   */
  const expect = JSON.stringify(state, null, 2)
  try {
    if (process.env.DSH_HOB_TEST_FAIL_ORCH_WRITE === '1') {
      throw new Error('orch-state-test-write-failed')
    }
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(tmp, expect, 'utf8')
    renameSync(tmp, file)
  } catch {
    try { rmSync(tmp, { force: true }) } catch { /* 清理失败不掩盖主错误 */ }
    return false
  }
  try {
    const back = readFileSync(file)
    if (!back.equals(Buffer.from(expect, 'utf8'))) return false
    return true
  } catch {
    /** ⚠ 读不回来 = 没确认 ⇒ 与"写失败"同档，⛔ 不许当成功。 */
    return false
  }
}

// ══════════════════════════════════════════════════════════════════════
// 写入前的**读盘守卫**：坏文件 / 版本不认识 ⇒ **拒写 + 留证**
// ══════════════════════════════════════════════════════════════════════

/**
 * ══════════════════════════════════════════════════════════════════════
 * ⚠⚠ **五个写路径的统一入口**（2026-10-24 · 本单必修 7 · `P3-①`）
 * ══════════════════════════════════════════════════════════════════════
 *
 * ── 治的缺陷 ──────────────────────────────────────────────────────────
 *   五个写函数（{@link recordHandoff} / {@link clearHandoffs} / {@link bindSession} /
 *   {@link writePending} / {@link markLostInner}）都是"**读 → 改 → 写**"，
 *   而"读"用的是 {@link readOrchState} —— 它的**宽容口径**把三件事读成同一个空态：
 *     · 文件真的还不存在（`ENOENT`）         —— 正常，"首次"；
 *     · 文件在、**读不了 / JSON 坏**         —— **危险**；
 *     · 文件在、**version 不认识**            —— **危险**。
 *   ⇒ 改前后果（`P3-①`）：
 *     后两种**照旧被当成空态**，然后 `writeOrchState` 把空态 + 本次改动**整份落盘**
 *     ⇒ ⚠ **一场坏 JSON / 一次版本漂移，就把盘上所有 pending / lost / handoffs / sessions
 *       一次性清空**，而五个函数都只是回 `wrote: true`。这就是"坏 JSON 清空"与
 *     "未知 version 静默降级重写"两条缺陷的同一处病根。
 *
 * ── 现在的判据（三档，⛔ 不许合并）───────────────────────────────────────
 *   · `ok`            —— 照旧走（读到的就是盘上那份）；
 *   · `no-records-yet` / `ledger-unreachable`（文件不存在）—— 照旧走（**首次创建**是正当路径）；
 *   · `unreadable` / `version-unknown` —— **拒写**，并把坏文件**另存一份留证**
 *     （`<file>.corrupt-<ts>`）。
 *
 * ⚠ ⚠ **为什么"留证"是必须的，不是锦上添花**：拒写之后，下一次写入仍会拒
 *   （文件还是坏的）⇒ 若不在第一次就把**原字节**留一份，运维想修就只能靠猜，
 *   而"拒写"会表现为"这个功能永远不记账"。留证让"盘上到底写坏了什么"可复核。
 * ⚠ **另存用复制而非改名**（`copyFileSync`）：⛔ 不动原文件 —— 原文件保持可读，
 *   `hob_orch_status` 的 `unreadable` 那一档**照旧报得出来**（改名会让它变成
 *   "没有记录"，那是把一种假信号换成另一种）。
 *
 * ⚠ **同一份坏文件只留证一次**（按"已留过"判：`<file>.corrupt-*` 里已经有一份与它
 *   字节相同的就不再复制）—— 否则每轮对账都会堆一份，把运行态目录撑爆。
 */
export type OrchWriteGuard =
  | { ok: true; reading: OrchStateReading }
  | { ok: false; reason: 'store-unreadable' | 'version-unknown'; message: string; evidence?: string }

/** 一次写入前守卫的**判据**（见 {@link readOrchStateForWrite} 的注释）。 */
export function readOrchStateForWrite(file: string): OrchWriteGuard {
  if (crossProcessDeniedFile === file) {
    return {
      ok: false,
      reason: 'store-unreadable',
      message: `拒绝写入：运行态文件 \`${file}\` 的跨进程 writer 锁未取得。`
        + '\n      ⇒ 另一个 live 进程可能正在写，或锁主判不出；本进程没有执行 read-modify-write。',
    }
  }
  const reading = readOrchStateDetailed(file)
  if (reading.reachability === 'unreadable') {
    const evidence = preserveCorruptCopy(file)
    return {
      ok: false,
      reason: 'store-unreadable',
      message: `拒绝写入：运行态文件 \`${file}\` **读不了 / 不是合法 JSON**`
        + '（账本根在、文件也在）。'
        + '\n      ⚠ 此时按空态重写会**把这个文件里原有的 pending / lost / handoffs / sessions 全部清空**，'
        + '而调用方只会看到"写成功" ⇒ 本函数**拒写**。'
        + (evidence === undefined
          ? '\n      ⚠ 留证副本没能生成（见上一条原因）—— 请人工备份后修 / 删该文件。'
          : `\n      ↳ 原字节已另存一份留证：\`${evidence}\`（⛔ 原文件一个字节都没动）`)
        + '\n      ⇒ 处置：人工检查该 JSON（或删掉它让运行态从空重建），然后再重试。',
      ...(evidence === undefined ? {} : { evidence }),
    }
  }
  if (reading.version !== undefined && !reading.version.known) {
    const evidence = preserveCorruptCopy(file)
    /**
     * ⚠ **"没有 version 字段"与"version 是别的值"要分开说**（两种成因，修法不同）：
     *   · 没有 ⇒ 这份文件**不是本模块写的**（本模块从第一天起就写 version）⇒ 先查是谁写的；
     *   · 是别的值 ⇒ **跨版本**（升级 / 降级 / 手工改）⇒ 先查版本再决定迁移。
     *   ⚠ 两者都**拒写**（都不许"当自己这一代"重写），但话术不许合成一句。
     */
    const shown = reading.version.found === undefined
      ? '文件里**没有** `version` 字段（不是本模块写的？）'
      : `文件里是 ${JSON.stringify(reading.version.found)}`
    return {
      ok: false,
      reason: 'version-unknown',
      message: `拒绝写入：运行态文件 \`${file}\` 的**结构版本不认识**`
        + `（${shown}；本插件只认 ${ORCH_STATE_VERSION}）。`
        + '\n      ⚠ 按"不认识就当我这一代"重写 = **静默降级**：旧/新版本里本代不认识的字段会被丢掉，'
        + '而盘上那份数据再也回不来（`P3-①` 点名的形态）⇒ 本函数**拒写**。'
        + (evidence === undefined ? '' : `\n      ↳ 原字节已另存一份留证：\`${evidence}\``)
        + '\n      ⇒ 处置：确认该版本由谁写（升级 / 降级 / 手工改），再决定迁移，⛔ 不要靠重写"修好"它。',
      ...(evidence === undefined ? {} : { evidence }),
    }
  }
  return { ok: true, reading }
}

/**
 * 把"读不了 / 版本不认识"的运行态文件**原字节另存一份**留证。
 *
 * @returns 留证文件的路径；**没能留证**时 `undefined`（⚠ 调用方必须把这件事说出来 —— 见下）。
 *
 * ⚠ **为什么不抛**：留证失败不该把"拒写"变成"崩溃"（拒写本身已经是安全的方向）。
 *   ⚠ 但⛔ 不许静默：{@link readOrchStateForWrite} 会把"没能留证"写进 message。
 * ⚠ **去重**：同目录下已有的 `*.corrupt-*` 里若有一份与当前字节相同 ⇒ **不再复制**
 *   （否则每轮对账都堆一份；留证是给"这一次写坏"用的，不是审计流水）。
 */
function preserveCorruptCopy(file: string): string | undefined {
  try {
    const dir = dirname(file)
    const base = file.slice(dir.length + 1)
    const prefix = `${base}.corrupt-`
    let bytes: Buffer
    try {
      bytes = readFileSync(file)
    } catch {
      /** ⚠ 连原字节都读不出来（EACCES）⇒ 留证做不到；由调用方在 message 里说清。 */
      return undefined
    }
    try {
      for (const n of readdirSync(dir)) {
        if (!n.startsWith(prefix)) continue
        try {
          if (readFileSync(join(dir, n)).equals(bytes)) return join(dir, n)
        } catch { /* 那份读不到 ⇒ 继续找 */ }
      }
    } catch { /* 目录列不出来 ⇒ 直接新建一份（下面会失败并如实返回 undefined） */ }
    const ts = new Date().toISOString().replace(/[:.]/g, '-')
    const dest = join(dir, `${prefix}${ts}`)
    copyFileSync(file, dest)
    /**
     * ⚠⚠ **D12 回读（2026-10-27 · 包 X）**：留证副本也是"改了盘上东西"的一处。
     *   ⚠ 它的返回值**被调用方当"留证成功"用**（写进 `refusal.evidence` 与 `message`）。
     *   ⇒ 复制完**独立回读**并与原字节比；不符 ⇒ 返回 `undefined`（= 留证做不到），
     *     由调用方在 message 里如实说清 —— ⛔ 不许拿"我调了 copy"当"证据在盘上"。
     *   ⚠ 读不到（EACCES）同样返回 `undefined`：那与"没复制成功"是同一档诚实边界。
     */
    try {
      if (!Buffer.from(readFileSync(dest)).equals(bytes)) return undefined
    } catch {
      return undefined
    }
    return dest
  } catch {
    return undefined
  }
}

/**
 * ── **拒写原因**的登记处（2026-10-24 · 本单必修 7 的"回可读原因"那一半）──────────
 *
 * ⚠ ⚠ **为什么需要它**：五个写函数的返回形状是**既有契约**（`boolean` 或
 *   `{ wrote, state }`…），而调用方全都在 `src/modules/**`（本单**不许改**）。
 *   ⇒ 拒写原因**不能塞进返回值的新字段里让调用方去读**（没人读 = 又是静默）；
 *   也不能为了回一句原因就把 `boolean` 改成对象（`if (!writePending(…))` 会
 *   把"真值对象"读成成功 —— 那是**更坏**的缺陷）。
 *   ⇒ 用一张**按文件 keyed 的登记表**：拒写时登记"为什么 / 证据在哪 / 什么时候"，
 *     由**读数面**（`hob_orch_status` 那一侧 / 机检）按文件查。
 *
 * ⚠ **它不是运行态数据**：只在**本进程内存**里（进程重载即清零）——
 *   拒写这件事本来就该在**下一次读数**里被看见；落盘会引入"写不进去还要写"的坑（同丙-1）。
 * ⚠ **成功写入会清掉该文件的登记**（"上一次拒了、这一次成了"不许一直挂着旧原因）。
 */
export interface OrchWriteRefusal {
  /** `store-unreadable` = 读不了 / 坏 JSON；`version-unknown` = 结构版本不认识。 */
  reason: 'store-unreadable' | 'version-unknown'
  /** 给人读的一整段（含处置建议）。 */
  message: string
  /** 另存的留证副本路径（没能留证 ⇒ 缺省，message 里会说明）。 */
  evidence?: string
  /** 拒写时刻（毫秒）。 */
  at: number
}

const writeRefusals = new Map<string, OrchWriteRefusal>()

/** 读**某个文件最近一次拒写**的原因（没有 ⇒ `undefined`）。 */
export function orchWriteRefusalOf(file: string): OrchWriteRefusal | undefined {
  return writeRefusals.get(file)
}

/** 全部登记（供读数面 / 机检一次性取；⚠ 返回副本，外部改不到内部表）。 */
export function orchWriteRefusals(): Array<{ file: string } & OrchWriteRefusal> {
  return [...writeRefusals.entries()].map(([file, r]) => ({ file, ...r }))
}

/**
 * 登记 / 清掉一次拒写（写入成功时清 —— 见 {@link OrchWriteRefusal} 的末条）。
 *
 * @returns 登记的那条**拒写原因**（成功 ⇒ `undefined`）。⚠ 有返回值的意义：那几个
 *   "返回对象"的写函数把它**同时**放进自己的返回值（`refusal` 字段）——
 *   既有的 `wrote` / `state` / `binding` 一个不动，读的人不必再去查登记表。
 */
function noteWriteOutcome(file: string, g: OrchWriteGuard): OrchWriteRefusal | undefined {
  if (g.ok) {
    writeRefusals.delete(file)
    return undefined
  }
  const rec: OrchWriteRefusal = {
    reason: g.reason,
    message: g.message,
    ...(g.evidence === undefined ? {} : { evidence: g.evidence }),
    at: Date.now(),
  }
  writeRefusals.set(file, rec)
  return rec
}

