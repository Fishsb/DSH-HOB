/**
 * **新建 Hob 会话的可读档「开放面」** —— 唯一落点。
 *
 * ══ 它管什么（⚠ 一句话，别扩大）════════════════════════════════════════
 *   **新建** Hob 会话时，哪些可读档是**当前允许**的。
 *   ⛔ 不管：已建会话的读档解析（那是 `session-policy.ts` 的事，三档仍都合法）、
 *   ⛔ 不管推进工作方式（三档照旧）、⛔ 不管非 Hob 会话（本机制不参与）。
 *
 * ══ 历史：2026-10-22 的「只开放最低档」裁定（⚠ 保留原文要点，别当成还没定过）══
 *   当时用户选「安全优先」：**新建会话只开放最低档（账本权限）**，另两档暂不开放。
 *   论证（⚠ 现在仍然成立，只是被下面的新裁定覆盖了风险取舍）：
 *     宿主**没有**持久删除会话的接口（`SessionPersistence` 只有 create/flush/list/open/stat）；
 *     撤出活会话只清内存，磁盘 JSONL 仍在 ⇒ 创建失败时若"策略隔离"与"宿主归档"同时写失败，
 *     已落盘的宽读档记录可能在重启后与磁盘会话**重新配对执行**。报警不等于修好。
 *   账本：`archive/2026-10-22-read-level-ceiling/USER-WORDS.md`。
 *
 * ══ 2026-10-24 本轮变更（用户裁定 2 · ⚠ 有意推翻上面那条，不是遗忘）══════════
 *   **开放面从只开最低档扩到三档全开（ledger + project + workspace）。**
 *   理由（用户视角）：只开最低档时，新建 Hob 会话**读不到工作区文件**，
 *   用户"建了会话却干不了活"，收益抵不过风险；用户本轮明确要求扩档。
 *   ⚠ 同时本轮补了**减少风险的两件事**（所以这次不是单纯的"把闸门拆了"）：
 *     ① 策略写入面（`session-policy-route.ts` 的 `action:'write'`）补上了
 *        「必须是非 Hob 拒绝 + 开放面校验」—— 扩档后 `project`/`workspace` 合法，
 *        但请求方仍然只能写这三档之一，⛔ 不能写任意字符串；
 *     ② 创建链的"隔离读回确认"收紧为**必须看到 `source==='quarantined'`**
 *        （以前任何 `ledger` 记录都算"已确认隔离"，会把假成功当真）。
 *
 * ══ 新的失效条件（⚠ 写在这里，防止有人以为"再也没有风险了"）════════════
 *   一旦**同时**出现下列两条，就应当把开放面**重新收紧**（改本文件这一处常量）：
 *     ① 创建失败后重载，宽读档记录与磁盘会话**重新配对**并被读/执行（实测复现）；
 *     ② 且"策略隔离 + 宿主归档"这一对兜底仍可能同时失败（即没有可靠持久清理）。
 *   ⇒ 收紧时同样**只改本文件这一处常量**（并把判据族一起改），
 *     ⛔ 不要在调用点各写一份白名单。
 *
 * ══ 为什么单独一个文件 ═════════════════════════════════════════════════
 *   这个"开放面"有**三个消费方、分属三个编译单元**：
 *     · host 半边 · 票据签发（`src/modules/session-create-channel.ts` 的 `issue()`）
 *     · host 半边 · 无界面建会话（`src/modules/bus.ts` 的 `hob_spawn`）
 *     · client 半边 · 弹窗（`src/client/create-hob-dialog.tsx` 只渲染服务下发的 `levels`）
 *   唯一值必须只有一处（防漂移），故放 `src/shared/`（两侧都能 import，实测 typecheck 过）。
 *
 * ⚠⚠ **服务端校验是唯一的门**：界面隐藏只是减少误操作 ——
 *   请求方自行报一个开放面外的值、或用旧票据重放，都必须由服务端拒
 *   （见上面两个消费点，以及本轮补闸的策略写入路由）。
 */
import { PERMISSION_LEVELS } from '../config.ts'
/**
 * ⚠ **能力红线句的单一来源**（2026-10-24 · 与 client 侧同一份）。
 *   `capability-red-line.ts` 是**零 import 的纯模块** ⇒ host / client 两侧都能 import。
 *   ⛔ 不要在本文件再抄一遍"不能写、不能执行命令、不能组队"的字面值：
 *     那句话原本有 9 处逐字副本，改一处漏一处**不会报错**（静默漂移）。
 */
import { CAPABILITY_RED_LINE_ZH } from './capability-red-line.ts'

/**
 * 新建 Hob 会话**当前开放**的可读档。
 *
 * 2026-10-24：由 `['ledger']` 扩为三档（用户裁定 2，见文件头"本轮变更"）。
 * ⚠ 这里用 `as const` 是为了让 `PERMISSION_LEVELS` 的子集关系可核。
 */
export const OPEN_READ_LEVELS = ['ledger', 'project', 'workspace'] as const

/** 开放面的元素类型（⚠ 从合法枚举里取，保证不会写出枚举外的值）。 */
export type OpenReadLevel = (typeof PERMISSION_LEVELS)[number]

/**
 * 用户可见的**原因说明**（⚠ 中文、无 markdown 标记、⛔ 不出现内部配置值）。
 *
 * ══ 为什么改名（2026-10-24）════════════════════════════════════════════
 *   原名 `CLOSED_READ_LEVEL_NOTE` 在"只开最低档"时代是对的（当时确有被**关闭**的档）。
 *   本轮扩档后三档全开，"closed"这个名字**已经与事实相反** ——
 *   ⚠ 留着一个名不副实的常量，下一个人读到名字就会以为"这里还有关闭的档"，
 *     进而照着旧语义写新判据（本仓最忌讳的静默漂移）。⇒ 改名 `OPEN_READ_LEVELS_NOTE`。
 *   ⚠ 引用点已全仓 grep 过，只有两处（`session-create-channel.ts` 的 `levelsNote` 下发、
 *     本文件的 `readLevelNotOpenReason`），均同步改完。
 *
 * ══ 文案口径（要经得起"读起来是事实"的检验）══════════════════════════════
 *   三档全开后用户读这句应当明白两件事：**三档都能选** + **三档都只读**。
 *   ⚠ 其中"都只读"那半句引用 `CAPABILITY_RED_LINE_ZH`（单一来源，
 *     与 client 弹窗 / 面板 / 配置表单同一份字面值）：那句话原本在仓库里有 9 处逐字副本，
 *     改一处漏一处**不会报错** ⇒ 属于本次要修的"静默漂移"。
 *     ⛔ 不要在这里再抄一遍那句话的字面值。
 *
 * ⚠ 它同时是弹窗的 `levelsNote`（`session-create-channel.ts` 下发）与拒绝理由的括号部分，
 *   ⇒ 两处口径必须一致（同一常量）。
 */
export const OPEN_READ_LEVELS_NOTE =
  `新建 Hob 会话当前开放三档可读范围：账本权限 / 文档权限 / 完全权限（三档都能选，且都只读：${CAPABILITY_RED_LINE_ZH}）。`

/**
 * ⚠ **没有保留旧名的别名**（有意，别"好心"加回来）：
 *   · 本仓**代码引用点已全部**改成新名（唯一两处：`session-create-channel.ts` 的 import +
 *     `levelsNote` 下发、本文件的 `readLevelNotOpenReason`）；剩下的命中**全是注释**
 *     （本文件记录改名历史的几行 + `create-hob-dialog.tsx:93` 那句待改的说明）；
 *   · 留一个零引用（代码零引用）的别名只会变成**死导出**，而且它的名字会让人以为
 *     "还有档被关闭"；
 *   · 若某个**仓外**调用方真的 import 了旧名 ⇒ 那是一次**编译期**失败（可发现、可修），
 *     ⛔ 比"它一直静默拿到一个已经不成立的措辞"好。
 */

/**
 * 某个档位是否属于**当前开放面**。
 *
 * ⚠ 判据是"在开放面里"，⛔ 不是"在合法枚举里" —— 今天两者恰好相同（三档全开），
 *   但**语义不同**：把两者混为一谈会让"重新收紧开放面"时调用点静默放行。
 *   ⇒ 调用方一律走本函数，⛔ 不要拿 `PERMISSION_LEVELS.includes()` 代替。
 */
export function isOpenReadLevel(level: unknown): boolean {
  return typeof level === 'string' && (OPEN_READ_LEVELS as readonly string[]).includes(level)
}

/**
 * 档位不在开放面时的**拒绝原因**（服务端用；⚠ 调用方须说清是拒签还是拒建）。
 *
 * @param action - 被拒的动作，如 `'签发一次性票据'` / `'创建会话'` / `'写入会话策略'`。
 */
export function readLevelNotOpenReason(action: string): string {
  return `可读档不在当前开放范围内 ⇒ 拒绝${action}（${OPEN_READ_LEVELS_NOTE}）`
}
